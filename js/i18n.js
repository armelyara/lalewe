const KEY = 'lalewe.lang';
let lang = CONFIG.defaultLang;
try {
  const saved = globalThis.localStorage?.getItem(KEY);
  if (saved && STRINGS[saved]) lang = saved;
} catch { /* storage unavailable: keep default */ }

export function getLang() {
  return lang;
}

export function setLang(next) {
  if (!STRINGS[next] || next === lang) return;
  lang = next;
  try { globalThis.localStorage?.setItem(KEY, next); } catch { /* ignore */ }
  globalThis.dispatchEvent?.(new Event('langchange'));
}

export function t(key, vars = {}) {
  const template = STRINGS[lang][key] ?? STRINGS.fr[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}
